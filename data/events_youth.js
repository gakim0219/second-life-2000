let reunionHook = null;
// love.js가 연결한다(성인 후보로 올리기). 순환 참조를 피하려고 바깥에서 넣는다.
export const onReunion = (fn) => { reunionHook = fn; };
let canAdult = () => false;
export const setAdultCheck = (fn) => { canAdult = fn; };
function reunionTarget(s) {
  const H = s.crush?.history ?? {};
  const ids = Object.entries(H).filter(([id, h]) => !h.reunion && ['사귐', '썸', '친한 사이'].includes(h.best) && canAdult(s, id)).sort((a, b) => (b[1].best === '사귐') - (a[1].best === '사귐')).map(([id]) => id);
  return ids[0] ?? null;
}

