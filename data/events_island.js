export function onMonth(s) {
  const x = G(s); if (!x) return s;
  if (s.flags.섬_멈춤) s.stress = Math.max(0, s.stress - 1);
  if (x.chair?.share && !s.ended) s.cash += SHARE_MONTHLY; // 물려받은 지분의 배당
  // 2020·2021년은 섬에 갈 수 없었고, 마지막 수업(2022)과 마지막 판(2025)이 있는 해는 그 장면이 대신한다.
  if (x.v5 && s.month === 8 && s.year <= 2025 && ![2020, 2021].includes(s.year) && !([2022, 2025].includes(s.year) && x.hyMet && s.flags.힐_계좌) && !x.sold && !inArmy(s) && m12(s) - x.v5 >= 11) { x.old += 1; x.visits += 1; (s.log ??= []).push('여름에 섬에 다녀왔습니다. 올해도 바둑은 한 판만 두었습니다.'); }
  return s;
}
