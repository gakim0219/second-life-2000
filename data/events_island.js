// ── 하연과의 석 달 대결 ──
export function duelResult(s) {
  const d = G(s)?.duel; if (!d?.base) return { win: false, mine: 0, hers: 0 };
  const mine = net(s) / d.base - 1, hers = 0.04 + hash(`${s.seed ?? 1}:duel`) * 0.06;
  return { win: mine > hers, mine, hers };
}

