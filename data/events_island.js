export function threeResult(s) {
  const x = G(s); if (!x?.pick || !inv.isLoaded()) return { win: null, ok: false };
  const y = Math.floor(x.pickAt / 12), m = (x.pickAt % 12) + 1;
  const rows = THREE.map(([id, name]) => { const a = inv.priceOfAt(id, y, m), b = inv.priceOfAt(id, y + 1, m); return { id, name, r: a > 0 && b > 0 ? b / a - 1 : -Infinity }; });
  const win = [...rows].sort((p, q) => q.r - p.r)[0];
  return { win, ok: win.r > -Infinity && win.id === x.pick };
}
